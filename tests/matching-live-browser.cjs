const {chromium} = require('@playwright/test');
const assert = require('node:assert/strict');

(async () => {
  const browser = await chromium.launch({headless:true});
  const page = await browser.newPage({viewport:{width:1440,height:900}});
  const errors=[];
  page.on('pageerror', e=>errors.push(e.message));
  await page.goto(process.argv[2] || 'http://100.104.11.94:8094');
  await page.waitForFunction(()=>document.querySelector('#connection').textContent==='Connecte');
  assert.equal(await page.locator('input[data-case]').count(),19);
  await page.locator('#select-all').uncheck();
  await page.locator('#max-tracks').fill('2');
  for(const id of ['spotify-album','manual-track']) await page.locator(`input[data-case="${id}"]`).check();
  await page.locator('[data-scenario="spotify-album"]').click();
  await page.locator('#start').click();
  await page.waitForFunction(()=>document.querySelector('#run-state').textContent==='Appariement en cours');
  await page.reload();
  await page.waitForFunction(()=>document.querySelector('#connection').textContent==='Connecte');
  assert.equal(await page.locator('input[data-case]:checked').count(),2);
  await page.waitForFunction(()=>document.querySelector('#run-state').textContent.startsWith('Termine'),{},{timeout:180000});
  assert.equal(await page.locator('#max-tracks').inputValue(),'2');
  assert.equal(await page.locator('#done').textContent(),'3 / 3');
  assert.equal(await page.locator('#matched').textContent(),'3');
  await page.screenshot({path:'/work/matching-live-desktop.png'});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'/work/matching-live-mobile.png'});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  assert(await page.locator('#table-region').evaluate(e=>e.clientHeight>=100));
  await page.setViewportSize({width:1440,height:900});
  const downloadPromise=page.waitForEvent('download');
  await page.locator('#download').click();
  assert.equal((await downloadPromise).suggestedFilename(),'inputs.json');
  await page.locator('#select-all').check();
  await page.locator('#select-all').uncheck();
  await page.locator('input[data-case="spotify"]').check();
  await page.locator('#max-tracks').fill('0');
  await page.locator('[data-scenario="spotify"]').click();
  await page.locator('#start').click();
  await page.waitForFunction(()=>document.querySelectorAll('.live-track-state.searching,.live-track-state.matched').length>0,{},{timeout:60000});
  await page.locator('#stop').click();
  await page.waitForFunction(()=>document.querySelector('#run-state').textContent==='Arrete',{},{timeout:60000});
  assert.equal(await page.locator('#start').isEnabled(),true);
  assert.deepEqual(errors,[]);
  console.log('Live matching: limit 2, 3/3 matches, reload, desktop/mobile, export and Docker cancellation OK');
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
